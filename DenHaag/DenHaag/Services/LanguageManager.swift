import SwiftUI

// MARK: - Supported Languages

enum AppLanguage: String, CaseIterable, Identifiable {
    case nl = "nl"
    case en = "en"
    case tr = "tr"

    var id: String { rawValue }

    var displayName: String {
        switch self {
        case .nl: return "Nederlands"
        case .en: return "English"
        case .tr: return "Türkçe"
        }
    }

    var flag: String {
        switch self {
        case .nl: return "🇳🇱"
        case .en: return "🇬🇧"
        case .tr: return "🇹🇷"
        }
    }
}

